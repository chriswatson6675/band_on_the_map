"use client";

import { useEffect, useMemo, useState } from "react";
import { DiscoveryMap, type MapMarker, type SearchArea } from "@/components/DiscoveryMap";
import { ALL_CITIES_AREA, getMarkersForArea } from "@/components/map-area.mjs";
import { resolveMapData } from "@/ingestion/map/runtime-publication.mjs";
import {
  filterMarkersByArtistId,
  filterMarkersByGenre,
  findArtistByExactName,
  searchArtists,
} from "@/ingestion/map/artist-genre-search.mjs";
import { filterMarkersByDateRange, resolveDefaultFromDate } from "@/ingestion/map/date-filter.mjs";
import { computeQuickDateRange } from "@/ingestion/map/quick-dates.mjs";
import publicationData from "@/data/public/lisbon-porto-map.json";

// Mirrors the publication artifact's own top-level `artists` search index
// (ingestion/map/publication.mjs's buildArtistIndex()) — not the full
// enriched Artist record, just enough for the search field below.
type ArtistIndexEntry = {
  artist_id: string;
  canonical_name: string;
  aliases: string[];
};

// data/public/lisbon-porto-map.json is the committed, BUNDLED-AT-BUILD-TIME
// fallback PRODUCT PUBLICATION ARTIFACT (BOTM-PUBLIC-MAP-LIVE-DATA-01) —
// generated by `npm run publish:map-data`/`npm run unattended` from the
// real, live Lisbon+Porto ingestion/display pipeline
// (ingestion/lisbon-porto/run.mjs + ingestion/map/publication.mjs), never
// hand-edited. See docs/PUBLIC_MAP_LIVE_DATA_01.md.
//
// BOTM-RUNTIME-PUBLICATION-BRIDGE-01: when
// NEXT_PUBLIC_BOTM_MAP_DATA_URL is configured, this page ALSO tries that
// runtime endpoint (ingestion/publication-server/run.mjs) client-side,
// AFTER the page has already been built/deployed — a fresh
// twice-daily-collected dataset can reach real visitors without a new Git
// commit or Netlify rebuild for every collection cycle. If that endpoint
// is unset, unreachable, slow, or returns anything that doesn't validate
// as a genuine publication artifact, this page keeps rendering the
// bundled dataset above — the map is never left blank because a runtime
// service happens to be temporarily down. See
// ingestion/map/runtime-publication.mjs and docs/RUNTIME_PUBLICATION_BRIDGE.md.
//
// The public homepage does not scrape venue websites. It renders the
// latest successfully published map dataset, runtime or bundled.
const BUNDLED_ARTIFACT = publicationData;
const RUNTIME_MAP_DATA_URL = process.env.NEXT_PUBLIC_BOTM_MAP_DATA_URL || null;

const genres = ["Any", "Rock", "Indie", "Alternative", "Electronic", "Jazz", "Folk", "Pop", "Metal"];
const quickDates = ["Tonight", "This weekend", "Next 7 days", "This month"];

// BEATMAPPED-DATE-FILTER-LIVE-01 — the ONE place this page reads the
// visitor's actual current calendar date, using LOCAL (not UTC) Date
// getters deliberately: this is genuinely "what calendar day is it for
// the person clicking Quick dates right now", not a pure data
// transform — ingestion/map/quick-dates.mjs's own computeQuickDateRange()
// takes this as a plain input and does every subsequent calculation in
// timezone-safe UTC-only arithmetic (see that module's own doc comment).
function getVisitorTodayDateString(): string {
  const now = new Date();
  const y = now.getFullYear();
  const m = String(now.getMonth() + 1).padStart(2, "0");
  const d = String(now.getDate()).padStart(2, "0");
  return `${y}-${m}-${d}`;
}

